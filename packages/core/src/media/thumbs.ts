import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { IndexStore } from '../index/store.js';
import type { ThumbSize } from './analyze.js';

const HASH = /^[0-9a-f]{64}$/;

/** Peers send thumbnails; a cache entry must be a WebP of sane size (HANDOFF §9: WebP only). */
export const MAX_THUMB_BYTES = 1024 * 1024;
export function isWebp(b: Uint8Array): boolean {
  return (
    b.length >= 12 &&
    b.length <= MAX_THUMB_BYTES &&
    Buffer.from(b.subarray(0, 4)).toString('latin1') === 'RIFF' &&
    Buffer.from(b.subarray(8, 12)).toString('latin1') === 'WEBP'
  );
}

/** `<dir>/ab/<hash>-<size>.webp`: two-level fan-out keeps directories small. */
function pathFor(dir: string, hash: string, size: number) {
  if (!HASH.test(hash)) throw new Error('bad hash');
  return join(dir, hash.slice(0, 2), `${hash}-${size}.webp`);
}

async function atomicWrite(path: string, data: Uint8Array) {
  await mkdir(join(path, '..'), { recursive: true });
  const tmp = `${path}.${process.pid}.${Date.now()}.tmp`;
  await writeFile(tmp, data);
  await rename(tmp, path);
}

/**
 * The owner's thumbnails of its own files, keyed by content hash (HANDOFF §9). Generated by
 * the media worker (320 px) or on demand (1600 px); served to peers on `thumb.get`.
 */
export class ThumbStore {
  constructor(readonly dir: string) {}

  async get(hash: string, size: ThumbSize): Promise<Buffer | null> {
    return readFile(pathFor(this.dir, hash, size)).catch(() => null);
  }

  async put(hash: string, size: ThumbSize, data: Uint8Array) {
    await atomicWrite(pathFor(this.dir, hash, size), data);
  }

  /** Deletes thumbnails of content no share holds any more. */
  async gc(live: Set<string>): Promise<number> {
    let removed = 0;
    for (const sub of await readdir(this.dir).catch(() => [] as string[])) {
      for (const f of await readdir(join(this.dir, sub)).catch(() => [] as string[])) {
        if (!live.has(f.slice(0, 64))) {
          await rm(join(this.dir, sub, f), { force: true });
          removed++;
        }
      }
    }
    return removed;
  }
}

/**
 * The viewer's cache of thumbnails fetched from peers, keyed by hash (content-addressed, so it's
 * shared across owners and hubs), least-recently-used entries evicted above `capBytes`.
 */
export class ThumbCache {
  constructor(
    readonly dir: string,
    private readonly store: IndexStore,
    public capBytes: number,
  ) {}

  has(hash: string, size: ThumbSize): boolean {
    return this.store.cacheHas(hash, size);
  }

  async get(hash: string, size: ThumbSize): Promise<Buffer | null> {
    if (!HASH.test(hash) || !this.store.cacheHas(hash, size)) return null;
    const data = await readFile(pathFor(this.dir, hash, size)).catch(() => null);
    if (!data) {
      this.store.cacheDrop(hash, size);
      return null;
    }
    this.store.cacheTouch(hash, size, data.length);
    return data;
  }

  /** Stores a peer's thumbnail; false (and nothing stored) if it isn't a sane WebP. */
  async put(hash: string, size: ThumbSize, data: Uint8Array): Promise<boolean> {
    if (!HASH.test(hash) || !isWebp(data)) return false;
    await atomicWrite(pathFor(this.dir, hash, size), data);
    this.store.cacheTouch(hash, size, data.length);
    await this.evict();
    return true;
  }

  private async evict() {
    let total = this.store.cacheTotal();
    while (total > this.capBytes) {
      const oldest = this.store.cacheOldest(64);
      if (oldest.length === 0) break;
      for (const o of oldest) {
        if (total <= this.capBytes) break;
        await rm(pathFor(this.dir, o.hash, o.size), { force: true });
        this.store.cacheDrop(o.hash, o.size);
        total -= o.bytes;
      }
    }
  }
}
